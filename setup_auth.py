#!/usr/bin/env python3
"""
setup_auth.py — Interactive password setup for CloudQuant on EC2.
Run this script DIRECTLY ON THE EC2 INSTANCE to set the login credentials.

Usage (on EC2, as ec2-user):
    python3.11 /home/ec2-user/cloudquant/setup_auth.py

It will:
1. Prompt for username (default: admin)
2. Prompt for a new password (hidden input, never echoed or logged)
3. Generate a bcrypt hash (cost factor 12)
4. Write .streamlit/secrets.toml with chmod 600 (owner-readable only)
5. Remind you to restart the service

SECURITY NOTES:
- The plaintext password is NEVER written to disk, only the bcrypt hash.
- This script should NOT be uploaded to S3 or committed to git
  (it contains no secrets itself, but its presence on S3 is unnecessary).
- The secrets.toml file it creates must never be committed to git or
  uploaded to S3.
"""

import getpass
import os
import sys
import pathlib

APP_DIR = pathlib.Path("/home/ec2-user/cloudquant")
SECRETS_DIR = APP_DIR / ".streamlit"
SECRETS_FILE = SECRETS_DIR / "secrets.toml"


def main() -> None:
    print("\n=== CloudQuant Authentication Setup ===\n")

    # Check bcrypt is available
    try:
        import bcrypt  # noqa: F401
    except ImportError:
        print("ERROR: bcrypt is not installed. Run:")
        print("  python3.11 -m pip install bcrypt")
        sys.exit(1)

    # Username
    username = input("Enter username (press Enter for default 'admin'): ").strip()
    if not username:
        username = "admin"
    if len(username) < 3 or len(username) > 64:
        print("ERROR: Username must be between 3 and 64 characters.")
        sys.exit(1)

    # Password
    print("\nPassword requirements: minimum 8 characters.")
    while True:
        password = getpass.getpass("Enter new password (hidden): ")
        if len(password) < 8:
            print("Password too short. Please use at least 8 characters.")
            continue
        confirm = getpass.getpass("Confirm password (hidden): ")
        if password != confirm:
            print("Passwords do not match. Try again.\n")
            continue
        break

    # Generate bcrypt hash
    import bcrypt
    password_hash = bcrypt.hashpw(
        password.encode("utf-8"), bcrypt.gensalt(rounds=12)
    ).decode("utf-8")

    # Immediately discard the plaintext
    del password, confirm

    # Write secrets.toml
    SECRETS_DIR.mkdir(parents=True, exist_ok=True)

    toml_content = (
        "# CloudQuant Authentication Secrets\n"
        "# Generated by setup_auth.py — DO NOT commit to git or upload to S3.\n\n"
        "[auth]\n"
        f'username = "{username}"\n'
        f'password_hash = "{password_hash}"\n'
    )

    SECRETS_FILE.write_text(toml_content)
    os.chmod(SECRETS_FILE, 0o600)  # owner-read/write only

    print(f"\n✅ Secrets written to: {SECRETS_FILE}")
    print(f"   File permissions: 600 (owner-read only)")
    print(f"   Username configured: {username}")
    print(f"   Password hash prefix: {password_hash[:10]}... (first 10 chars only, never share)")
    print("\n--- Next step ---")
    print("Restart the Streamlit service to apply the new credentials:")
    print("  sudo systemctl restart cloudquant")
    print()


if __name__ == "__main__":
    main()

